# -*- coding: utf-8 -*-
"""
scripts/bootstrap_ci_secrets.py
--------------------------------
Restores Blogger OAuth files (credentials.json, token.json) and SEO.env
from GitHub Actions secrets in the runner environment.
"""

import os
import sys
try:
    sys.stdout.reconfigure(encoding='utf-8')
except Exception:
    pass
import json

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def bootstrap():
    print("🔐 [CI Bootstrap] 환경 변수로부터 보안 키 복원 시작...")
    
    # 1. Restore credentials.json
    creds_raw = os.getenv("BLOGGER_CREDENTIALS_JSON", "")
    creds_path = os.path.join(BASE_DIR, "credentials.json")
    if creds_raw:
        try:
            creds_data = json.loads(creds_raw)
            with open(creds_path, "w", encoding="utf-8") as f:
                json.dump(creds_data, f, indent=2)
            print("   ✓ credentials.json 복원 성공")
        except Exception as e:
            print(f"   ❌ credentials.json 파싱 실패: {e}")
            sys.exit(1)
    elif os.path.exists(creds_path):
        print("   ℹ️ credentials.json 파일이 이미 로컬에 존재합니다.")
    else:
        print("   ⚠️ BLOGGER_CREDENTIALS_JSON 환경변수가 설정되지 않았습니다.")

    # 2. Restore token.json
    token_raw = os.getenv("BLOGGER_TOKEN_JSON", "")
    token_path = os.path.join(BASE_DIR, "token.json")
    if token_raw:
        try:
            token_data = json.loads(token_raw)
            with open(token_path, "w", encoding="utf-8") as f:
                json.dump(token_data, f, indent=2)
            print("   ✓ token.json 복원 성공")
        except Exception as e:
            print(f"   ❌ token.json 파싱 실패: {e}")
            sys.exit(1)
    elif os.path.exists(token_path):
        print("   ℹ️ token.json 파일이 이미 로컬에 존재합니다.")
    else:
        print("   ⚠️ BLOGGER_TOKEN_JSON 환경변수가 설정되지 않았습니다.")

    # 3. Restore SEO.env
    env_path = os.path.join(BASE_DIR, "SEO.env")
    openrouter_key = os.getenv("OPENROUTER_API_KEY", "")
    blog_id = os.getenv("BLOGGER_BLOG_ID", "2002031376804677477")
    cse_cx = os.getenv("GOOGLE_CSE_CX", "863c2f0c96b064551")
    is_adsense = os.getenv("IS_ADSENSE_APPROVED", "false")

    if openrouter_key:
        env_content = f"""# Auto-generated by CI Bootstrap
OPENROUTER_API_KEY={openrouter_key}
BLOGGER_BLOG_ID={blog_id}
GOOGLE_CSE_CX={cse_cx}
IS_ADSENSE_APPROVED={is_adsense}
"""
        with open(env_path, "w", encoding="utf-8") as f:
            f.write(env_content)
        print("   ✓ SEO.env 복원 성공")
    elif os.path.exists(env_path):
        print("   ℹ️ SEO.env 파일이 이미 로컬에 존재합니다.")
    else:
        print("   ⚠️ OPENROUTER_API_KEY 환경변수가 설정되지 않았습니다.")

    print("🔐 [CI Bootstrap] 보안 부트스트랩 완료 (Exit Code 0)\n")

if __name__ == "__main__":
    bootstrap()
